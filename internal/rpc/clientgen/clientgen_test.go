package clientgen

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const testAPI = `package store

import (
	"context"
	"encoding/json"
	"time"
)

type API interface {
	CreateBead(ctx context.Context, nb NewBead, actor string) (*Bead, error)
	GetBead(ctx context.Context, id string) (*Bead, error)
	Ready(ctx context.Context) ([]Bead, error)

	AddDep(ctx context.Context, from, to, kind, at, until, actor string) error
	MarkRunning(ctx context.Context, sessionID string, handle map[string]any) error
	AddNotedAs(ctx context.Context, id, text, actor, session string, files ...string) (*Note, error)
	Claim(ctx context.Context, beadID, group, stage, actor string, via ...Routed) (*Session, error)
	PeerSend(ctx context.Context, name, kind string, body json.RawMessage, actor string) (*PeerOut, error)
	FireTimers(ctx context.Context, at time.Time) (*TimerPass, error)
	BlockerCycles(ctx context.Context) ([][]string, error)
	RecordPack(ctx context.Context, rec PackImport, changed bool, actor string) (bool, error)

	Conversation(ctx context.Context, a, b string, after uint64, limit int, before uint64) ([]Letter, bool, error)
	Subscribe(ctx context.Context, after uint64) (<-chan Event, error)
	TailEvents(ctx context.Context) (<-chan Event, error)
	Wake(ctx context.Context) (<-chan struct{}, error)
	Close(ctx context.Context) error
}
`

func generate(t *testing.T, src string) string {
	t.Helper()
	out, err := Generate(writeAPI(t, src))
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	return string(out)
}

func writeAPI(t *testing.T, src string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "api.go")
	if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

// The wrappers read as the handwritten ones did: the signature as the
// interface has it, store's types named, and the one line through callV or
// c.call.
func TestGenerateWrappers(t *testing.T) {
	got := generate(t, testAPI)
	for _, want := range []string{
		"func (c *Client) CreateBead(ctx context.Context, nb store.NewBead, actor string) (*store.Bead, error) {\n\treturn callV[*store.Bead](c, ctx, \"CreateBead\", nb, actor)\n}",
		"func (c *Client) AddDep(ctx context.Context, from, to, kind, at, until, actor string) error {\n\treturn c.call(ctx, \"AddDep\", nil, from, to, kind, at, until, actor)\n}",
		"func (c *Client) Ready(ctx context.Context) ([]store.Bead, error) {\n\treturn callV[[]store.Bead](c, ctx, \"Ready\")\n}",
		// A variadic slice goes as its list, the one value the server spreads again.
		"func (c *Client) AddNotedAs(ctx context.Context, id, text, actor, session string, files ...string) (*store.Note, error) {\n\treturn callV[*store.Note](c, ctx, \"AddNotedAs\", id, text, actor, session, files)\n}",
		"func (c *Client) Claim(ctx context.Context, beadID, group, stage, actor string, via ...store.Routed) (*store.Session, error) {\n\treturn callV[*store.Session](c, ctx, \"Claim\", beadID, group, stage, actor, via)\n}",
		// Selectors keep their import; maps, slices and nesting qualify within.
		"func (c *Client) PeerSend(ctx context.Context, name, kind string, body json.RawMessage, actor string) (*store.PeerOut, error) {",
		"func (c *Client) FireTimers(ctx context.Context, at time.Time) (*store.TimerPass, error) {",
		"func (c *Client) MarkRunning(ctx context.Context, sessionID string, handle map[string]any) error {",
		"func (c *Client) BlockerCycles(ctx context.Context) ([][]string, error) {",
		"func (c *Client) RecordPack(ctx context.Context, rec store.PackImport, changed bool, actor string) (bool, error) {",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("generated file lacks:\n%s\n got:\n%s", want, got)
		}
	}
	// The bespoke stay handwritten: no wrapper, and the file still needs
	// every import a kept method reached.
	for _, name := range []string{"Subscribe", "TailEvents", "Wake", "Close", "Conversation"} {
		if strings.Contains(got, `"`+name+`"`) {
			t.Errorf("generated file wraps bespoke %s", name)
		}
	}
	for _, imp := range []string{`"context"`, `"encoding/json"`, `"time"`, `"yardr.dev/yardr/internal/store"`} {
		if !strings.Contains(got, imp) {
			t.Errorf("generated file lacks import %s:\n%s", imp, got)
		}
	}
	if !strings.HasPrefix(got, "// Code generated by go generate ./internal/rpc; DO NOT EDIT.") {
		t.Errorf("generated file lacks the generated header:\n%s", got)
	}
}

// A method of a shape the generator does not know is an error, not a wrong
// wrapper.
func TestGenerateUnknownShape(t *testing.T) {
	src := strings.Replace(testAPI, "\tReady(ctx context.Context) ([]Bead, error)\n",
		"\tReady(ctx context.Context) ([]Bead, bool, error)\n", 1)
	if _, err := Generate(writeAPI(t, src)); err == nil {
		t.Error("Generate of a three-result method succeeded")
	} else if !strings.Contains(err.Error(), "Ready") {
		t.Errorf("Generate error names no method: %v", err)
	}
}

// A bespoke the interface no longer has is an error: a rename must move the
// handwritten method, not silently gain a generated one.
func TestGenerateMissingBespoke(t *testing.T) {
	src := strings.Replace(testAPI, "\tClose(ctx context.Context) error\n", "", 1)
	if _, err := Generate(writeAPI(t, src)); err == nil {
		t.Error("Generate without Close succeeded")
	} else if !strings.Contains(err.Error(), "Close") {
		t.Errorf("Generate error names no method: %v", err)
	}
}
