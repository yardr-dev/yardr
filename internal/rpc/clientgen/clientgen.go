// Package clientgen writes the rpc client's mechanical store.API wrappers:
// one per interface method, through callV or c.call. go generate runs it
// (internal/rpc/gen); a test holds the committed file to its output.
package clientgen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"maps"
	"os"
	"slices"
	"strings"
)

// bespoke are the store.API methods with handwritten wrappers in
// internal/rpc/client.go: the streams and lifecycle, which the server does
// not serve through /call (rpc.notCallable), and Conversation, whose
// partial-list answer is decoded through part.more.
var bespoke = map[string]bool{
	"Subscribe":    true,
	"TailEvents":   true,
	"Wake":         true,
	"Close":        true,
	"Conversation": true,
}

// predeclared are the type names qualification leaves alone: what api.go
// names bare otherwise is store's.
var predeclared = map[string]bool{
	"bool": true, "byte": true, "complex64": true, "complex128": true,
	"error": true, "float32": true, "float64": true,
	"int": true, "int8": true, "int16": true, "int32": true, "int64": true,
	"rune": true, "string": true,
	"uint": true, "uint8": true, "uint16": true, "uint32": true, "uint64": true,
	"uintptr": true, "any": true, "comparable": true,
}

// storePath is the import path qualification gives a bare type name.
const storePath = "yardr.dev/yardr/internal/store"

// Generate returns client_gen.go as the generator writes it, from the
// store.API interface in the Go source file apiPath: one wrapper per
// method but the bespoke, in the interface's order. A method of a shape
// the generator does not know (today, anything but (T, error) and error)
// is an error, not a wrong wrapper: extend the generator or handwrite the
// method in client.go and name it in bespoke.
func Generate(apiPath string) ([]byte, error) {
	src, err := os.ReadFile(apiPath)
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, apiPath, src, parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}
	pkgs := map[string]string{} // package name -> import path
	for _, imp := range f.Imports {
		path := strings.Trim(imp.Path.Value, `"`)
		name := path[strings.LastIndex(path, "/")+1:]
		if imp.Name != nil {
			if imp.Name.Name == "_" || imp.Name.Name == "." {
				return nil, fmt.Errorf("clientgen: %s imports %s as %s", apiPath, path, imp.Name.Name)
			}
			name = imp.Name.Name
		}
		pkgs[name] = path
	}
	var iface *ast.InterfaceType
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range gd.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok || ts.Name.Name != "API" {
				continue
			}
			iface, _ = ts.Type.(*ast.InterfaceType)
		}
	}
	if iface == nil {
		return nil, fmt.Errorf("clientgen: %s has no API interface", apiPath)
	}
	used := map[string]bool{} // import paths but store's a wrapper reached
	var b strings.Builder
	prevEnd := -1
	seen := map[string]bool{}
	for _, field := range iface.Methods.List {
		if len(field.Names) != 1 {
			return nil, fmt.Errorf("clientgen: the API embeds %s: extend the generator", formatExpr(fset, field.Type))
		}
		name := field.Names[0].Name
		seen[name] = true
		if bespoke[name] {
			continue
		}
		ft, ok := field.Type.(*ast.FuncType)
		if !ok || ft.Params == nil {
			return nil, fmt.Errorf("clientgen: %s is no method", name)
		}
		start := fset.Position(field.Pos()).Line
		if field.Doc != nil {
			start = fset.Position(field.Doc.Pos()).Line
		}
		if prevEnd >= 0 && start-prevEnd > 1 {
			b.WriteString("\n")
		}
		prevEnd = fset.Position(field.End()).Line
		wrapper, err := method(fset, name, ft, pkgs, used)
		if err != nil {
			return nil, fmt.Errorf("clientgen: %s: %w", name, err)
		}
		b.WriteString(wrapper)
	}
	for name := range bespoke {
		if !seen[name] {
			return nil, fmt.Errorf("clientgen: bespoke %s is no method of the API", name)
		}
	}
	var out strings.Builder
	out.WriteString("// Code generated by go generate ./internal/rpc; DO NOT EDIT.\n\npackage rpc\n\nimport (\n")
	std, rest := []string{}, []string{}
	for _, path := range slices.Sorted(maps.Keys(used)) {
		if strings.Contains(path, ".") {
			rest = append(rest, path)
		} else {
			std = append(std, path)
		}
	}
	for _, path := range std {
		fmt.Fprintf(&out, "\t%q\n", path)
	}
	if len(std) > 0 && len(rest) > 0 {
		out.WriteString("\n")
	}
	for _, path := range rest {
		fmt.Fprintf(&out, "\t%q\n", path)
	}
	out.WriteString(")\n\n")
	out.WriteString(b.String())
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("clientgen: the generated file does not format: %w", err)
	}
	return formatted, nil
}

// method is the wrapper for one interface method: its signature as api.go
// reads, with store's types named, and the one line through callV or c.call.
func method(fset *token.FileSet, name string, ft *ast.FuncType, pkgs map[string]string, used map[string]bool) (string, error) {
	params := ft.Params.List
	if len(params) == 0 {
		return "", fmt.Errorf("no context")
	}
	first, err := qualify(fset, params[0].Type, pkgs, used)
	if err != nil {
		return "", err
	}
	if first != "context.Context" || len(params[0].Names) != 1 || params[0].Names[0].Name != "ctx" {
		return "", fmt.Errorf("first parameter is no ctx context.Context")
	}
	var sig, args []string
	sig = append(sig, "ctx context.Context")
	for _, p := range params[1:] {
		t, err := qualify(fset, p.Type, pkgs, used)
		if err != nil {
			return "", err
		}
		var names []string
		for _, n := range p.Names {
			names = append(names, n.Name)
			args = append(args, n.Name)
		}
		sig = append(sig, strings.Join(names, ", ")+" "+t)
	}
	var results, body string
	switch {
	case ft.Results == nil || len(ft.Results.List) == 0:
		return "", fmt.Errorf("answers nothing: extend the generator")
	case len(ft.Results.List) == 1 && len(ft.Results.List[0].Names) == 0:
		t, err := qualify(fset, ft.Results.List[0].Type, pkgs, used)
		if err != nil {
			return "", err
		}
		if t != "error" {
			return "", fmt.Errorf("answers %s with no error: extend the generator", t)
		}
		results = " error"
		body = fmt.Sprintf(`return c.call(ctx, %q, nil%s)`, name, callArgs(args))
	case len(ft.Results.List) == 2 && len(ft.Results.List[0].Names) == 0 && len(ft.Results.List[1].Names) == 0:
		t, err := qualify(fset, ft.Results.List[0].Type, pkgs, used)
		if err != nil {
			return "", err
		}
		last, err := qualify(fset, ft.Results.List[1].Type, pkgs, used)
		if err != nil {
			return "", err
		}
		if last != "error" {
			return "", fmt.Errorf("answers (%s, %s): extend the generator", t, last)
		}
		results = fmt.Sprintf(" (%s, error)", t)
		body = fmt.Sprintf(`return callV[%s](c, ctx, %q%s)`, t, name, callArgs(args))
	default:
		return "", fmt.Errorf("answers more than a value and an error: handwrite it in client.go")
	}
	return fmt.Sprintf("func (c *Client) %s(%s)%s {\n\t%s\n}\n", name, strings.Join(sig, ", "), results, body), nil
}

// callArgs is the arguments after the method name: a variadic slice goes as
// its list, the one JSON value the server's invoke spreads again.
func callArgs(args []string) string {
	if len(args) == 0 {
		return ""
	}
	return ", " + strings.Join(args, ", ")
}

// qualify renders a type of api.go as it reads in package rpc: what api.go
// names bare is store's, and what it names through another import stays
// named so. used gains every import path but store's a type reached.
func qualify(fset *token.FileSet, e ast.Expr, pkgs map[string]string, used map[string]bool) (string, error) {
	rw, err := rewrite(e, pkgs, used)
	if err != nil {
		return "", err
	}
	return formatExpr(fset, rw), nil
}

func formatExpr(fset *token.FileSet, e ast.Expr) string {
	var buf bytes.Buffer
	_ = format.Node(&buf, fset, e)
	return buf.String()
}

// rewrite names store's types for package rpc: a bare identifier that is no
// predeclared name becomes store's, and a selector keeps the import it names.
func rewrite(e ast.Expr, pkgs map[string]string, used map[string]bool) (ast.Expr, error) {
	switch t := e.(type) {
	case *ast.Ident:
		if predeclared[t.Name] {
			return t, nil
		}
		if _, ok := pkgs[t.Name]; ok {
			return nil, fmt.Errorf("bare package name %q is no type", t.Name)
		}
		used[storePath] = true
		return &ast.SelectorExpr{X: ast.NewIdent("store"), Sel: ast.NewIdent(t.Name)}, nil
	case *ast.SelectorExpr:
		id, ok := t.X.(*ast.Ident)
		if !ok {
			return nil, fmt.Errorf("selector on no package")
		}
		path, ok := pkgs[id.Name]
		if !ok {
			return nil, fmt.Errorf("selector on unknown package %q", id.Name)
		}
		used[path] = true
		return e, nil
	case *ast.StarExpr:
		x, err := rewrite(t.X, pkgs, used)
		if err != nil {
			return nil, err
		}
		return &ast.StarExpr{X: x}, nil
	case *ast.ArrayType:
		elt, err := rewrite(t.Elt, pkgs, used)
		if err != nil {
			return nil, err
		}
		return &ast.ArrayType{Len: t.Len, Elt: elt}, nil
	case *ast.MapType:
		k, err := rewrite(t.Key, pkgs, used)
		if err != nil {
			return nil, err
		}
		v, err := rewrite(t.Value, pkgs, used)
		if err != nil {
			return nil, err
		}
		return &ast.MapType{Key: k, Value: v}, nil
	case *ast.Ellipsis:
		elt, err := rewrite(t.Elt, pkgs, used)
		if err != nil {
			return nil, err
		}
		return &ast.Ellipsis{Elt: elt}, nil
	case *ast.ChanType:
		v, err := rewrite(t.Value, pkgs, used)
		if err != nil {
			return nil, err
		}
		return &ast.ChanType{Dir: t.Dir, Value: v}, nil
	case *ast.ParenExpr:
		return rewrite(t.X, pkgs, used)
	default:
		return nil, fmt.Errorf("type %T: extend the generator", e)
	}
}
